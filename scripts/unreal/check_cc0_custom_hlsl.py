"""Compile the CC0 environment masters' Custom HLSL on the host with the pinned engine's DXC.

Each entry of ``cc0_environment_hlsl.CUSTOM`` is wrapped exactly as the UE 5.8
material translator wraps a Custom expression (``translator_function``) and
called from one pixel shader, which is compiled with the engine's own
``libdxcompiler`` for SPIR-V (the front end of the Metal and Vulkan paths) and
for DXIL (D3D12), under HLSL 2018 and 2021. A deliberately broken node must
fail first, so the check cannot pass vacuously.

This checks the hand-written HLSL and its declared pin types only. The rest of
each material is generated by the engine and is compiled only when an editor
with a renderer (or a cook) builds the shader maps.

    python3 scripts/unreal/check_cc0_custom_hlsl.py
"""

from __future__ import annotations

import ctypes
import os
from pathlib import Path
import sys
import uuid

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cc0_environment_hlsl import CUSTOM, Custom, translator_function  # noqa: E402
from sora_engine_pin import PIN, require_engine_root  # noqa: E402

DXC_LIBRARY = "Engine/Binaries/ThirdParty/ShaderConductor/Mac/libdxcompiler.dylib"
ENTRY = "SoraCustomHlslCheck"
TARGETS = (
    ("SPIR-V", ("-T", "ps_6_0", "-spirv", "-fspv-target-env=vulkan1.1", "-fvk-use-scalar-layout")),
    ("DXIL", ("-T", "ps_6_0", "-Vd")),  # no DXIL validator ships for macOS; code generation still runs
)
HLSL_VERSIONS = ("2018", "2021")

# The declarations the translated material provides to Custom expression functions.
PRELUDE = """
#define MaterialFloat float
#define MaterialFloat2 float2
#define MaterialFloat3 float3
#define MaterialFloat4 float4
struct FMaterialPixelParameters { float4 SvPosition; };
struct FWSVector3 { float3 High; float3 Low; };
FWSVector3 SoraWSVector3(float3 Value) { FWSVector3 Result; Result.High = Value; Result.Low = 0.0; return Result; }
"""
_SWIZZLE = {"float": ".x", "float2": ".xy", "float3": ".xyz", "float4": ""}


def shader_source(customs: list[Custom]) -> str:
    """One pixel shader that calls every Custom function with varying inputs and sums what they return."""
    functions = [translator_function(custom, index) for index, custom in enumerate(customs)]
    body = ["    float3 Sum = 0.0;", "    FMaterialPixelParameters Parameters;",
            "    Parameters.SvPosition = SvPosition;"]
    widen = {"float": ".xxx", "float2": ".xyx", "float3": ""}
    for index, custom in enumerate(customs):
        arguments = ["Parameters"]
        for number, (_, kind) in enumerate(custom.inputs):
            source = ("A", "B")[number % 2]
            if kind == "lwc3":
                arguments += [f"{source}.xyz", f"SoraWSVector3({source}.xyz * 100000.0)"]
            else:
                arguments.append(f"{source}{_SWIZZLE[kind]}")
        for name, kind in custom.outputs:
            body.append(f"    {kind} {name}{index} = 0.0;")
            arguments.append(f"{name}{index}")
        body.append(f"    {custom.output} Result{index} = CustomExpression{index}({', '.join(arguments)});")
        body.append(f"    Sum += Result{index}{widen[custom.output]};")
        body += [f"    Sum += {name}{index}{widen[kind]};" for name, kind in custom.outputs]
    entry = (f"float4 {ENTRY}(float4 SvPosition : SV_Position, float4 A : TEXCOORD0, float4 B : TEXCOORD1)"
             " : SV_Target0\n{\n" + "\n".join(body) + "\n    return float4(Sum, 1.0);\n}\n")
    return PRELUDE + "\n" + "\n".join(functions) + "\n" + entry


class _Guid(ctypes.Structure):
    _fields_ = [("data1", ctypes.c_uint32), ("data2", ctypes.c_uint16), ("data3", ctypes.c_uint16),
                ("data4", ctypes.c_ubyte * 8)]

    @classmethod
    def parse(cls, text):
        value, guid = uuid.UUID(text), cls()
        guid.data1, guid.data2, guid.data3 = value.fields[:3]
        guid.data4[:] = value.bytes[8:]
        return guid


class _Buffer(ctypes.Structure):
    _fields_ = [("pointer", ctypes.c_void_p), ("size", ctypes.c_size_t), ("encoding", ctypes.c_uint32)]


CLSID_DXC_COMPILER = _Guid.parse("73e22d93-e6ce-47f3-b5bf-f0664f39c1b0")
IID_DXC_COMPILER3 = _Guid.parse("228b4687-5a6a-4730-900c-9702b2203f54")
IID_DXC_RESULT = _Guid.parse("58346cda-dde7-4497-9461-6f87af5e0659")
UTF8 = 65001


def _method(interface, slot, restype, *argtypes):
    """A COM method: DXC's macOS IUnknown has QueryInterface, AddRef and Release, so methods start at slot 3."""
    table = ctypes.cast(interface, ctypes.POINTER(ctypes.POINTER(ctypes.c_void_p))).contents
    return ctypes.CFUNCTYPE(restype, ctypes.c_void_p, *argtypes)(table[slot])


def _release(interface):
    if interface.value:
        _method(interface, 2, ctypes.c_uint32)(interface)


def _blob_bytes(blob) -> bytes:
    pointer = _method(blob, 3, ctypes.c_void_p)(blob)
    size = _method(blob, 4, ctypes.c_size_t)(blob)
    return ctypes.string_at(pointer, size) if size else b""


class Dxc:
    def __init__(self, library: Path):
        self.library = ctypes.CDLL(str(library))
        create = self.library.DxcCreateInstance
        create.restype = ctypes.c_int32
        create.argtypes = [ctypes.POINTER(_Guid), ctypes.POINTER(_Guid), ctypes.POINTER(ctypes.c_void_p)]
        self.compiler = ctypes.c_void_p()
        status = create(CLSID_DXC_COMPILER, IID_DXC_COMPILER3, ctypes.byref(self.compiler))
        if status != 0 or not self.compiler.value:
            raise RuntimeError(f"DxcCreateInstance failed: 0x{status & 0xFFFFFFFF:08x}")

    def compile(self, source: str, arguments: list[str]) -> tuple[bool, int, str]:
        """(succeeded, object size in bytes, compiler messages)."""
        text = source.encode()
        buffer = _Buffer(ctypes.cast(ctypes.c_char_p(text), ctypes.c_void_p), len(text), UTF8)
        wide = (ctypes.c_wchar_p * len(arguments))(*arguments)
        result = ctypes.c_void_p()
        compile_ = _method(self.compiler, 3, ctypes.c_int32, ctypes.POINTER(_Buffer), ctypes.c_void_p,
                           ctypes.c_uint32, ctypes.c_void_p, ctypes.POINTER(_Guid), ctypes.POINTER(ctypes.c_void_p))
        call = compile_(self.compiler, ctypes.byref(buffer), ctypes.cast(wide, ctypes.c_void_p), len(arguments),
                        None, ctypes.byref(IID_DXC_RESULT), ctypes.byref(result))
        if call != 0 or not result.value:
            raise RuntimeError(f"IDxcCompiler3::Compile failed: 0x{call & 0xFFFFFFFF:08x}")
        status, errors, output = ctypes.c_int32(), ctypes.c_void_p(), ctypes.c_void_p()
        _method(result, 3, ctypes.c_int32, ctypes.POINTER(ctypes.c_int32))(result, ctypes.byref(status))
        _method(result, 5, ctypes.c_int32, ctypes.POINTER(ctypes.c_void_p))(result, ctypes.byref(errors))
        _method(result, 4, ctypes.c_int32, ctypes.POINTER(ctypes.c_void_p))(result, ctypes.byref(output))
        messages = _blob_bytes(errors).decode(errors="replace").strip() if errors.value else ""
        size = len(_blob_bytes(output)) if output.value else 0
        for interface in (output, errors, result):
            _release(interface)
        return status.value == 0 and size > 0, size, messages


def arguments(target: tuple, version: str) -> list[str]:
    return ["-E", ENTRY, *target, "-HV", version, "-Qunused-arguments", "-Wno-unknown-attributes"]


def main() -> int:
    engine_root = Path(os.environ.get("UE_ROOT", PIN["default_macos_root"])).expanduser()
    require_engine_root(engine_root)
    dxc = Dxc(engine_root / DXC_LIBRARY)
    customs = list(CUSTOM.values())
    broken = Custom("broken swizzle", "return N.xyzw;", "float3", (("N", "float3"),))
    for name, target in TARGETS:
        ok, _, messages = dxc.compile(shader_source([broken]), arguments(target, HLSL_VERSIONS[-1]))
        if ok or "out of bounds" not in messages:
            print(f"SORA_CC0_HLSL_FAILED: the {name} negative control compiled or failed for another reason: "
                  f"{messages[:400]}", file=sys.stderr)
            return 1
    source = shader_source(customs)
    failures, sizes = [], []
    for name, target in TARGETS:
        for version in HLSL_VERSIONS:
            ok, size, messages = dxc.compile(source, arguments(target, version))
            if messages:
                print(f"{name} HLSL {version} messages:\n{messages}", file=sys.stderr)
            if not ok:
                failures.append(f"{name} HLSL {version}")
            sizes.append(f"{name}/{version} {size} B")
    if failures:
        print(f"SORA_CC0_HLSL_FAILED: {', '.join(failures)}", file=sys.stderr)
        return 1
    print(f"SORA_CC0_HLSL_COMPILED: {len(customs)} Custom expressions "
          f"({', '.join(custom.description for custom in customs)}) as {', '.join(sizes)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
