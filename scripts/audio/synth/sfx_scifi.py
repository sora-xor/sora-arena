def engine_core_loop(r, v):
    """Flagship 『複利号』 engine room (ch07): sub fundamental, coil whine, air handling, ticks."""
    n = n_of(12.0)
    idx = np.arange(n)
    base = 41.2
    hum = sum(loop_osc(n, base * k, r.uniform(0, 6.28)) * (1 / k ** 1.1) for k in (1, 2, 3, 4, 6, 8))
    hum += loop_osc(n, base + 0.25) * 0.5  # quantised -> slow beat
    whine_f = qf(1174.7, n)
    vib = 3.0 * np.sin(2 * np.pi * qf(0.25, n) * idx / SR)
    ph = 2 * np.pi * np.cumsum(whine_f + vib) / SR
    whine = np.sin(ph) * 0.05 * loop_lfo(n, 0.5)
    air = circular_band_noise(n, r, 80, 700, -3) * 0.35 + circular_band_noise(n, r, 2500, 7000) * 0.04
    # mechanical ticks every 0.5 s (repeats exactly per loop)
    tick = modal(n_of(0.12), [2100, 3900, 6100], [0.04, 0.03, 0.02], [1, 0.5, 0.3], r)
    ticks = np.zeros(n)
    pattern = [1.0, 0.35, 0.6, 0.35] * 6
    for k, a in enumerate(pattern):
        place_circular(ticks, tick * a * 0.12, n_of(0.5 * k))
    glass = np.zeros(n)
    for t0, f in [(1.7, 1318.5), (5.9, 987.8), (9.3, 1567.98)]:
        place_circular(glass, glass_partials(r, f, n_of(3.5), 1.4, 5) * 0.05, n_of(t0))
    y = hum * 0.45 * (0.9 + 0.1 * loop_osc(n, 0.5)) + whine + air + ticks + glass
    return finish_loop(y, r, 0.4, space('engine'), 0.25)


def ledger_engine_loop(r, v):
    """Reckoning / Ledger Engine (ch07.b06, ch08): mechanical ostinato in 5 built from abacus-bead
    clicks over a drum rumble; 5/8 at 150 eighths per minute (2.0 s bar), 4 bars."""
    bar = 2.0
    n = n_of(bar * 4)
    y = np.zeros(n)
    eighth = bar / 5
    accents = [1.0, 0.45, 0.7, 0.45, 0.55]
    for b in range(4):
        for k in range(5):
            for sub in range(2):
                t0 = b * bar + k * eighth + sub * eighth / 2
                a = accents[k] * (1.0 if sub == 0 else 0.35)
                bead = modal(n_of(0.06), 3100 * np.array([1, 2.1, 3.7]) * (1 + 0.02 * r.normal()), [0.02, 0.012, 0.008], [1, 0.4, 0.2], r)
                place_circular(y, bead * a * 0.35, n_of(t0))
    drum = loop_osc(n, 55) * 0.35 * (0.6 + 0.4 * loop_lfo(n, 2.5)) + circular_band_noise(n, r, 30, 160) * 0.25
    ring = circular_band_noise(n, r, 400, 2400) * 0.12 * (loop_lfo(n, 0.5) ** 2)
    out = y + drum + ring
    return finish_loop(out, r, 0.4, space('engine'), 0.2)


