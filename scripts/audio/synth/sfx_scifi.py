"""Original sci-fi sound design (tier OWN): Credit House weapons, energy beam, shields / barriers and
alien machinery. The invaders' palette is "cold": glassy inharmonic partials, precise pulses, clean
sub-bass and high-voltage crackle, never warm or organic (story bible §15; chapter 7 §5.7).

Loops are built to be sample-exact periodic: every oscillator frequency and LFO rate is quantised to an
integer number of cycles per loop, noise is generated by circular FFT filtering, and reverb is applied
by circular convolution. The wrap point is therefore seamless by construction (QA re-checks it).
"""
from __future__ import annotations

import numpy as np

from dsp import (SR, apply_reverb, bandpass, bell_curve, circ, circular_band_noise, crackle, crackle_periodic, env_exp,
                 place_circular,
                 env_points, fade, fm, highpass, lowpass, mix, modal, n_of, pan, phase_from_freq, pink, reverb_ir, rng,
                 time_axis, tv_filter, white, widen)

_IRS = {}


def space(name):
    if name not in _IRS:
        cfg = {
            'outdoor': (0.7, 0.5, 20, 2.0),
            'hangar': (2.6, 0.75, 18, 1.6),
            'engine': (1.8, 0.6, 10, 1.2),
            'vault': (3.2, 0.4, 25, 1.8),
            'glass': (1.6, 0.95, 6, 0.8),
        }[name]
        _IRS[name] = reverb_ir(cfg[0], rng('ir-' + name), bright=cfg[1], predelay_ms=cfg[2], size=cfg[3])
    return _IRS[name]


def qf(f: float, n: int) -> float:
    """Quantise a frequency to an integer number of cycles over n samples (seamless loops)."""
    cycles = max(1, round(f * n / SR))
    return cycles * SR / n


def loop_osc(n: int, f: float, phase: float = 0.0) -> np.ndarray:
    return np.sin(2 * np.pi * qf(f, n) * np.arange(n) / SR + phase)


def loop_lfo(n: int, rate: float, phase: float = 0.0) -> np.ndarray:
    return 0.5 + 0.5 * loop_osc(n, rate, phase)


def glass_partials(r, f0: float, n: int, t60: float, count: int = 6) -> np.ndarray:
    """Inharmonic 'cold glass' cluster (thin-film black glass, cyan ledger emissives)."""
    ratios = np.array([1.0, 1.593, 2.136, 2.917, 3.598, 4.37, 5.41, 6.83])[:count]
    freqs = f0 * ratios * (1 + r.normal(0, 0.003, ratios.size))
    return modal(n, freqs, t60 * np.linspace(1, 0.35, ratios.size), np.linspace(1, 0.3, ratios.size), r, attack=0.004)


def norm(x):
    return x / (np.max(np.abs(x)) + 1e-12)


def finish_loop(y: np.ndarray, r, width: float, ir: np.ndarray, wet: float) -> np.ndarray:
    """Stereo-ise and add space to a periodic mono loop without breaking periodicity."""
    return circ(lambda s: apply_reverb(widen(s, r, width), ir, wet), y)


