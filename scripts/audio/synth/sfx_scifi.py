def barrier_break(r, v):
    dur = 2.4
    n = n_of(dur)
    parts = []
    for k in range(38):
        t0 = abs(r.normal(0, 0.18)) + 0.01 * k * r.random()
        f = r.uniform(900, 6000)
        shard = glass_partials(r, f, n_of(0.6), r.uniform(0.08, 0.35), 4) * r.uniform(0.2, 0.8) * np.exp(-t0 * 3)
        parts.append((pan(shard, r.uniform(-0.9, 0.9)), n_of(t0)))
    burst = pan(highpass(white(n_of(0.2), r), 700) * env_exp(n_of(0.2), 0.06), 0) * 0.9
    down = pan(fm(700 * (0.08 + 0.92 * env_exp(n, 0.4)), 1.5, 2.5 * env_exp(n, 0.3)) * env_exp(n, 0.6), 0) * 0.35
    sub = pan(np.sin(phase_from_freq(60 * (1 + env_exp(n_of(0.6), 0.05)))) * env_exp(n_of(0.6), 0.35), 0) * 0.8
    y = mix(n, (burst, 0), (down, 0), (sub, 0), *parts)
    return apply_reverb(fade(y, 0.0005, 0.4), space('glass'), 0.2)


