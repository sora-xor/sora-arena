def shock_emitter_loop(r, v):
    """Shock Emitter (catalog 16) sustained arc: seamless 3.0 s loop of buzz + crackle."""
    n = n_of(3.0)
    hum = sum(loop_osc(n, 100 * k, r.uniform(0, 6.28)) / k ** 1.2 for k in range(1, 12))
    hum = circ(lambda x: lowpass(x, 4000), hum) * (0.6 + 0.4 * loop_lfo(n, 7))
    dens = 2500 * (0.5 + 0.5 * loop_lfo(n, 2, 1.0)) * (0.6 + 0.4 * loop_lfo(n, 11))
    crackle_loop = crackle_periodic(n, r, dens, 900, 13000, 0.0008)
    zaps = circular_band_noise(n, r, 1500, 9000) * (loop_lfo(n, 13) ** 6) * 0.5
    y = hum * 0.35 + norm(crackle_loop) * 0.6 + zaps
    return finish_loop(y, r, 0.5, space('outdoor'), 0.08)


