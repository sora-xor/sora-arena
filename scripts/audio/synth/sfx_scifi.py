def plasma_charge(r, v):
    """Plasma Matchlock charge to full (catalog 14): rising whine, tightening tremolo, lock click."""
    dur = 1.55
    n = n_of(dur)
    t = np.linspace(0, 1, n)
    f = 180 * (10 ** (1.05 * t ** 1.4))  # 180 Hz -> ~2 kHz
    trem_rate = 6 + 34 * t ** 2
    trem = 0.75 + 0.25 * np.sin(phase_from_freq(trem_rate))
    whine = fm(f, 2.0, 0.8 + 1.8 * t) * trem * (0.2 + 0.8 * t ** 1.2)
    sizzle = tv_filter(white(n, r), 'bandpass', 1500 + 7000 * t, 2.0) * (t ** 2) * 0.6
    sub = np.sin(phase_from_freq(45 + 25 * t)) * (0.3 + 0.7 * t) * 0.5
    y = whine + sizzle + sub
    y *= env_points(n, [(0, 0), (0.05, 1), (dur, 1)])
    # full-charge lock
    lock = mix(n_of(0.3), (modal(n_of(0.3), [2350, 4800, 7300], [0.08, 0.05, 0.03], [1, 0.6, 0.3], r), 0),
               (highpass(white(n_of(0.004), r), 3000) * env_exp(n_of(0.004), 0.001), 0))
    out = mix(n + n_of(0.35), (y * 0.6, 0), (lock * 0.8, n - n_of(0.01)))
    out = fade(out, 0.002, 0.04)
    return apply_reverb(widen(out, r, 0.4), space('outdoor'), 0.08)


def plasma_hold_loop(r, v):
    """Charged and held: unstable coil hum (seamless 2.0 s loop)."""
    n = n_of(2.0)
    base = qf(1850, n)
    wob = 1 + 0.004 * np.sin(2 * np.pi * qf(5, n) * np.arange(n) / SR)
    ph = 2 * np.pi * np.cumsum(base * wob) / SR
    tone = np.sin(ph + 1.2 * np.sin(2 * ph))
    trem = 0.7 + 0.3 * loop_osc(n, 38)
    sizzle = circular_band_noise(n, r, 5000, 12000) * 0.25 * loop_lfo(n, 3)
    sub = loop_osc(n, 70) * 0.45
    y = tone * trem * 0.45 + sizzle + sub
    return finish_loop(y, r, 0.3, space('outdoor'), 0.06)


def plasma_fire(r, v):
    """Plasma Matchlock discharge: crack + ionised bolt (downward FM) + sub + metallic ring + air tail."""
    dur = 1.6
    n = n_of(dur)
    crack = highpass(white(n_of(0.012), r), 900) * env_exp(n_of(0.012), 0.004) * 1.4
    fb = 2400 * (0.06 + 0.94 * env_exp(n_of(0.35), 0.12)) * (1 + 0.03 * v)
    bolt = fm(fb, 1.41, 3.0 * env_exp(fb.size, 0.1)) * env_exp(fb.size, 0.22)
    sub = np.sin(phase_from_freq(55 * (1 + 1.5 * env_exp(n_of(0.5), 0.05)))) * env_exp(n_of(0.5), 0.3)
    ring = glass_partials(r, 520 + 40 * v, n_of(1.2), 0.7) * 0.25
    ion = crackle(n_of(0.6), r, 6000 * env_exp(n_of(0.6), 0.2), 3000, 14000, 0.0005) * 1.5
    air = bandpass(pink(n, r), 200, 3000) * env_points(n, [(0, 0), (0.01, 1), (dur, 0)], 'linear') ** 3 * 0.35
    blast = bandpass(white(n_of(0.12), r), 500, 3500) * env_exp(n_of(0.12), 0.05)
    y = mix(n, (crack, 0), (blast * 0.8, 0), (bolt * 0.9, 0), (sub * 0.6, 0), (ring, n_of(0.005)), (norm(ion) * 0.3, 0),
            (air, 0))
    y = fade(y, 0.0005, 0.2)
    return apply_reverb(widen(y, r, 0.45), space('outdoor'), 0.18)


