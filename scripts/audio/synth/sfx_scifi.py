def beam_loop(r, v):
    """Collector locked-aim beam (Val Amort P1, boss telegraph cyan): seamless 4.0 s loop."""
    n = n_of(4.0)
    core = sum(loop_osc(n, f, r.uniform(0, 6.28)) * a for f, a in [(73.4, 1.0), (146.8, 0.5), (220.2, 0.3), (293.6, 0.2)])
    beating = loop_osc(n, 1174.7) * 0.2 + loop_osc(n, 1177.2) * 0.2  # quantised pair -> slow beat
    glassy = sum(loop_osc(n, 1174.7 * rt) * 0.06 / i for i, rt in enumerate([1.593, 2.136, 2.917], 1))
    plasma = circular_band_noise(n, r, 1800, 7000) * 0.35 * (0.6 + 0.4 * loop_lfo(n, 17))
    throb = 0.8 + 0.2 * loop_osc(n, 6)
    y = (core * 0.45 + beating + glassy) * throb + plasma
    return finish_loop(y, r, 0.45, space('hangar'), 0.12)


