//! Frozen first-release reference weapon/class data. Balancing changes change rules identity.

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum AttackKind {
    Melee,
    Hitscan,
    Projectile,
}

#[derive(Debug, Clone, Copy)]
pub struct Weapon {
    pub id: u8,
    pub name: &'static str,
    pub kind: AttackKind,
    pub damage: i32,
    pub range_mm: i32,
    pub cooldown: u16,
    pub stamina: i32,
    pub projectile_mm_tick: i32,
    pub blast_mm: i32,
    pub arming_mm: i32,
    pub charge_ticks: u16,
    pub magazine: u16,
    pub reload_ticks: u16,
}

#[expect(
    clippy::too_many_arguments,
    reason = "Frozen weapon table explicitly specifies each proof-bound parameter"
)]
const fn w(
    id: u8,
    name: &'static str,
    kind: AttackKind,
    damage: i32,
    range_mm: i32,
    cooldown: u16,
    stamina: i32,
    velocity: i32,
    blast: i32,
    arming: i32,
    charge: u16,
    magazine: u16,
    reload_ticks: u16,
) -> Weapon {
    Weapon {
        id,
        name,
        kind,
        damage,
        range_mm,
        cooldown,
        stamina,
        projectile_mm_tick: velocity,
        blast_mm: blast,
        arming_mm: arming,
        charge_ticks: charge,
        magazine,
        reload_ticks,
    }
}
